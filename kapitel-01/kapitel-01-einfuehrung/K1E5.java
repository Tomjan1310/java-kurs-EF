/**
 * Führt einfache Rechnungen mit Variablen durch.
 */
public class K1E5 {
  public static void main(String[] args) {
    int zahl1 = 21;
    int zahl2 = 3;
    int zahl3 = 17;
    int zahl4 = 4;

    int ergebnis = zahl1 * zahl2 + zahl3 * zahl4;

    System.out.println("Das Ergebnis ist: " + ergebnis);
  }
}